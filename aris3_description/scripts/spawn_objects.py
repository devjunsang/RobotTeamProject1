# ============================================================
# 9. 이 코드를 작성한 이유
# ============================================================
#
# ARIS3 프로젝트의 최종 목표는 로봇팔이 특정 색상의
# 물체를 인식하고, 해당 위치로 이동하여 집는 것이다.
#
# 이를 위해서는 먼저 Gazebo 가상 환경에
# 위치와 크기가 정해진 물체가 존재해야 한다.
#
# 물체를 하나씩 수동으로 배치하는 방식은
# 반복 실험과 좌표 수정이 불편하다.
#
# 따라서 CSV 파일을 이용하여 객체의 배치 정보를
# 관리하고, Python을 통해 Gazebo 모델을 자동으로
# 생성하기 위해 이 코드를 작성하였다.
#
#
# ============================================================
# 10. 이 코드가 수행하는 작업
# ============================================================
#
# 첫째, CSV에서 객체의 위치와 색상 정보를 읽는다.
#
# 둘째, 정육면체의 물리 속성과 시각적 형상을 정의한다.
#
# 셋째, Gazebo에서 사용할 수 있는 SDF 파일을 생성한다.
#
# 넷째, --spawn 옵션이 있으면 Gazebo에 객체 생성을 요청한다.
#
# 다섯째, 이후 RViz2와 MoveIt 2에서도 활용할 수 있는
# 일관된 객체 배치 정보를 제공하는 기초를 마련한다.
#
# 단, 이 코드 자체는 RViz2 마커나 MoveIt Planning Scene에
# 객체를 자동으로 등록하지 않는다.
#
