# 명령줄 인자(--spawn 등)를 처리하는 표준 라이브러리
import argparse

# CSV 형식의 파일을 읽기 위한 표준 라이브러리
import csv

# 수학 계산에 사용하는 라이브러리
# 현재 코드에서는 직접 사용하지 않음
import math

# Python 코드에서 외부 명령어를 실행하기 위한 라이브러리
# 예: ros2 run ros_gz_sim create
import subprocess

# 파일 및 폴더 경로를 편리하게 다루기 위한 클래스
from pathlib import Path

# XML 구조를 생성하거나 검사하기 위한 라이브러리
# 여기서는 SDF 파일이 올바른 XML인지 검사하는 데 사용
import xml.etree.ElementTree as ET


# ------------------------------------------------------------
# 2. 프로젝트 경로 설정
# ------------------------------------------------------------

# Path.home()은 현재 사용자의 홈 디렉터리를 반환한다.
# 예: /home/junsang
#
# / 연산자를 사용하면 경로를 안전하게 이어 붙일 수 있다.
ROOT = Path.home() / "WorkPlace/ARIS/ARIS3"

# 객체들의 배치 정보가 저장된 CSV 파일 경로
#
# CSV에는 객체 이름, 색상, X/Y/Z 좌표,
# 가로 크기, 높이 등이 저장되어 있다.
CSV = ROOT / "config/object_layout.csv"

# 생성된 SDF 모델들을 저장할 폴더
#
# /tmp는 임시 파일 디렉터리이므로
# 시스템 재부팅 시 파일이 삭제될 수 있다.
OUTPUT = Path("/tmp/aris3_objects")


# ------------------------------------------------------------
# 3. 객체 색상 정보 정의
# ------------------------------------------------------------

# Python의 딕셔너리(Dictionary) 자료형
#
# key   : 색상 이름
# value : RGBA 색상 값
#
# RGBA = Red, Green, Blue, Alpha
#
# 각 숫자의 범위는 일반적으로 0.0 ~ 1.0
# Alpha 값 1은 완전 불투명을 의미한다.
COLORS = {
    "red":    "1 0 0 1",  # 빨강
    "blue":   "0 0 1 1",  # 파랑
    "yellow": "1 1 0 1",  # 노랑 = 빨강 + 초록
    "green":  "0 1 0 1",  # 초록
}


# ------------------------------------------------------------
# 4. 생성할 객체 이름 정의
# ------------------------------------------------------------

# set 자료형은 중복된 값을 허용하지 않는다.
#
# CSV에 정확히 이 네 가지 객체가 존재하는지
# 확인하는 데 사용한다.
EXPECTED = {
    "red_box",
    "blue_box",
    "yellow_box",
    "green_box",
}


# ------------------------------------------------------------
# 5. Gazebo SDF 모델 생성 함수
# ------------------------------------------------------------

# def는 Python에서 함수를 정의할 때 사용한다.
#
# row는 CSV 파일에서 읽어 온 한 객체의 정보이다.
#
# 예:
# row = {
#     "name": "red_box",
#     "color": "red",
#     "x": "0.45",
#     "y": "0.18",
#     "z": "0.02",
#     "width": "0.04",
#     "height": "0.04"
# }
#
# 함수의 반환값은 SDF 형식의 문자열이다.
def generate_sdf(row):

    # 객체 이름을 가져온다.
    name = row["name"]

    # 객체 색상을 가져온다.
    color = row["color"]

    # CSV는 숫자도 문자열로 읽기 때문에
    # float()을 사용하여 실수형으로 변환한다.

    # 객체의 X 좌표 (단위: m)
    x = float(row["x"])

    # 객체의 Y 좌표 (단위: m)
    y = float(row["y"])

    # 객체의 Z 좌표 (단위: m)
    z = float(row["z"])

    # 정육면체의 가로 및 세로 길이
    width = float(row["width"])

    # 정육면체의 높이
    height = float(row["height"])

    # 설정된 색상이 COLORS에 존재하는지 확인한다.
    #
    # 존재하지 않으면 ValueError 예외를 발생시켜
    # 잘못된 색상의 모델이 생성되는 것을 방지한다.
    if color not in COLORS:
        raise ValueError(f"지원하지 않는 색상: {color}")

    # 객체 크기는 반드시 0보다 커야 한다.
    #
    # width 또는 height가 0 이하라면
    # 올바른 3D 모델을 생성할 수 없다.
    if width <= 0 or height <= 0:
        raise ValueError(f"잘못된 객체 크기: {name}")

    # --------------------------------------------------------
    # 5-1. 물리 속성 설정
    # --------------------------------------------------------

    # 객체의 질량을 0.08 kg(80 g)으로 설정
    mass = 0.08

    # 직육면체의 X축 및 Y축 관성모멘트 계산
    #
    # 직육면체의 관성모멘트 공식:
    #
    # Ixx = m * (y² + z²) / 12
    # Iyy = m * (x² + z²) / 12
    #
    # 여기서는 x, y 방향 길이가 width로 같으므로
    # 두 관성모멘트가 동일하다.
    ixy = mass * (width**2 + height**2) / 12

    # Z축 관성모멘트 계산
    #
    # Izz = m * (x² + y²) / 12
    #
    # x = y = width이므로:
    # Izz = m * width² / 6
    izz = mass * width**2 / 6

    # --------------------------------------------------------
    # 5-2. SDF 문자열 작성
    # --------------------------------------------------------

    # f""" ... """은 여러 줄로 된 문자열을 생성한다.
    #
    # 문자열 안의 {name}, {mass} 등은
    # Python 변수 값으로 자동 치환된다.
    #
    # SDF(Simulation Description Format)는
    # Gazebo에서 모델의 구조와 물리 속성을 정의하는 형식이다.
    sdf = f"""<?xml version="1.0"?>
<sdf version="1.9">

  <!-- 모델 하나의 시작 -->
  <model name="{name}">

    <!-- 모델 내부 기준 자세: 원점 -->
    <!-- 최종 월드 위치는 create 명령의 -x, -y, -z로 지정 -->
    <pose>0 0 0 0 0 0</pose>

    <!--
      static=false
      중력과 충돌 등 물리 시뮬레이션의 영향을 받는다.
    -->
    <static>false</static>

    <!-- 실제 물리 형상을 가지는 링크 -->
    <link name="body">

      <!-- 질량 및 관성 정보 -->
      <inertial>

        <!-- 질량 (kg) -->
        <mass>{mass}</mass>

        <!-- 관성모멘트 (kg·m²) -->
        <inertia>
          <ixx>{ixy}</ixx>
          <iyy>{ixy}</iyy>
          <izz>{izz}</izz>

          <!-- 대칭 형상이며 축이 일치하므로 0 -->
          <ixy>0</ixy>
          <ixz>0</ixz>
          <iyz>0</iyz>
        </inertia>

      </inertial>

      <!--
        Collision
        물리 엔진이 충돌을 계산할 때 사용하는 형상
      -->
      <collision name="collision">

        <geometry>
          <box>
            <!-- 가로 세로 높이 (m) -->
            <size>{width} {width} {height}</size>
          </box>
        </geometry>

      </collision>

      <!--
        Visual
        Gazebo 화면에 실제로 보이는 형상
      -->
      <visual name="visual">

        <geometry>
          <box>
            <!-- 화면에 보이는 정육면체 크기 -->
            <size>{width} {width} {height}</size>
          </box>
        </geometry>

        <!-- 객체 표면의 색상 설정 -->
        <material>

          <!-- 주변광에 반응하는 색상 -->
          <ambient>{COLORS[color]}</ambient>

          <!-- 직접 조명에 반응하는 색상 -->
          <diffuse>{COLORS[color]}</diffuse>

        </material>

      </visual>

    </link>

  </model>

</sdf>
"""

    # 완성된 SDF XML 문자열을 호출한 곳으로 반환한다.
    return sdf


# ------------------------------------------------------------
# 6. 프로그램 메인 함수
# ------------------------------------------------------------

# main()은 프로그램의 전체 실행 과정을 관리한다.
def main():

    # 명령줄 옵션을 해석하기 위한 객체 생성
    parser = argparse.ArgumentParser()

    # --spawn 옵션 등록
    #
    # action="store_true"의 의미:
    #
    # --spawn을 입력하면 True
    # 입력하지 않으면 False
    parser.add_argument(
        "--spawn",
        action="store_true",
        help="Gazebo에 객체를 실제 생성",
    )

    # 사용자가 입력한 실행 옵션을 읽어 온다.
    args = parser.parse_args()

    # --------------------------------------------------------
    # 6-1. CSV 파일 존재 여부 검사
    # --------------------------------------------------------

    # CSV 파일이 없으면 다음 작업을 진행할 수 없다.
    if not CSV.is_file():
        raise RuntimeError(f"CSV 없음: {CSV}")

    # --------------------------------------------------------
    # 6-2. 출력 디렉터리 생성
    # --------------------------------------------------------

    # SDF 파일을 저장할 폴더를 만든다.
    #
    # parents=True:
    # 상위 폴더가 없으면 함께 생성한다.
    #
    # exist_ok=True:
    # 이미 폴더가 있어도 오류를 발생시키지 않는다.
    OUTPUT.mkdir(parents=True, exist_ok=True)

    # --------------------------------------------------------
    # 6-3. CSV 데이터 읽기
    # --------------------------------------------------------

    # with 문은 파일 작업이 끝나면
    # 파일을 자동으로 닫도록 도와준다.
    #
    # encoding="utf-8"은 문자 인코딩을 지정한다.
    with CSV.open(encoding="utf-8") as f:

        # DictReader는 CSV의 첫 줄을 열 이름으로 사용한다.
        #
        # 각 행을 딕셔너리 형태로 반환한다.
        #
        # list()를 이용하여 모든 행을 리스트에 저장한다.
        rows = list(csv.DictReader(f))

    # 모든 객체의 name 값만 추출한다.
    #
    # 리스트 컴프리헨션(List Comprehension) 문법
    names = [row["name"] for row in rows]

    # --------------------------------------------------------
    # 6-4. 객체 구성 검사
    # --------------------------------------------------------

    # 조건 1: 객체가 정확히 4개인가?
    # 조건 2: 객체 이름이 예상 목록과 일치하는가?
    #
    # 두 조건 중 하나라도 만족하지 않으면 중단한다.
    if len(rows) != 4 or set(names) != EXPECTED:
        raise RuntimeError("객체 4개 구성이 올바르지 않습니다.")

    # --------------------------------------------------------
    # 6-5. 각 객체에 대해 SDF 생성
    # --------------------------------------------------------

    # for 문을 이용해 CSV의 4개 행을 순서대로 처리한다.
    for row in rows:

        # 현재 처리 중인 객체 이름
        name = row["name"]

        # 객체별 SDF 파일 경로 생성
        #
        # 예: /tmp/aris3_objects/red_box.sdf
        path = OUTPUT / f"{name}.sdf"

        # generate_sdf(row):
        # 현재 객체의 SDF XML 문자열 생성
        #
        # write_text():
        # 생성된 문자열을 파일로 저장
        path.write_text(
            generate_sdf(row),
            encoding="utf-8",
        )

        # ----------------------------------------------------
        # 6-6. XML 문법 검사
        # ----------------------------------------------------

        # SDF 파일을 XML 파서로 읽는다.
        #
        # XML 문법이 잘못되면 예외가 발생한다.
        #
        # 주의:
        # XML 문법 검사이므로 SDF의 물리적 타당성까지
        # 보장하는 것은 아니다.
        ET.parse(path)

        # SDF 생성 성공 메시지 출력
        #
        # flush=True:
        # 출력 버퍼에 보관하지 않고 즉시 표시하도록 요청
        print(f"[PASS] SDF 생성: {name}", flush=True)

        # ----------------------------------------------------
        # 6-7. Gazebo 객체 생성
        # ----------------------------------------------------

        # --spawn 옵션을 입력했을 때만 실행한다.
        #
        # 옵션이 없다면 SDF 파일 생성까지만 수행한다.
        if args.spawn:

            # Gazebo에 객체를 생성하는 ROS 2 명령어
            #
            # ros2 run ros_gz_sim create
            #
            # -world: 사용할 Gazebo 월드
            # -name : 생성할 모델 이름
            # -file : 읽어 올 SDF 파일
            # -x    : 모델 X 위치
            # -y    : 모델 Y 위치
            # -z    : 모델 Z 위치
            cmd = [
                "ros2", "run", "ros_gz_sim", "create",
                "-world", "empty",
                "-name", name,
                "-file", str(path),
                "-x", str(row["x"]),
                "-y", str(row["y"]),
                "-z", str(row["z"]),
            ]

            # 외부 명령어를 실제 실행한다.
            #
            # check=True:
            # 명령어가 0이 아닌 종료 코드로 끝나면
            # CalledProcessError 예외를 발생시킨다.
            #
            # 이 호출은 명령이 종료될 때까지 기다린다.
            subprocess.run(cmd, check=True)

            # Gazebo 생성 명령 성공 메시지 출력
            print(f"[SPAWNED] {name}", flush=True)

    # 모든 객체에 대한 처리가 끝난 후 출력
    print("[PASS] ARIS3 객체 처리 완료", flush=True)


# ------------------------------------------------------------
# 7. 프로그램 진입점
# ------------------------------------------------------------

# Python 파일을 직접 실행하면 __name__은 "__main__"이다.
#
# 예:
# python3 spawn_objects.py --spawn
#
# 다른 Python 파일에서 import하는 경우에는
# 아래 main()이 자동 실행되지 않는다.
if __name__ == "__main__":
    main()


