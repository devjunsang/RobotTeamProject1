# 13. 주의사항
# ============================================================
#
# 1. Gazebo 객체 좌표는 기본적으로 월드 좌표를 기준으로
#    해석되므로, base_link와의 관계를 확인해야 한다.
#
# 2. 물체의 Z 좌표가 지면보다 낮으면 물체가 묻힐 수 있다.
#
# 3. 동적 모델은 물리 시뮬레이션에 따라 움직일 수 있다.
#
# 4. 현재 SDF와 create 명령 양쪽에 위치가 설정되어 있다.
#    실제 최종 위치는 Gazebo에서 Pose를 확인해야 한다.
#
# 5. 현재 코드의 XML 검사는 SDF의 의미론적 검증이나
#    로봇과 물체 사이의 충돌 검증을 수행하지 않는다.
#
# 6. 기존 객체가 남아 있으면 재생성 시 이름 충돌이
#    발생할 수 있으므로 월드 상태를 확인해야 한다.
